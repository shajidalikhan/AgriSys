"""Pydantic schemas for the Diagram Agent."""

from __future__ import annotations
from enum import Enum
from typing import Any
from pydantic import BaseModel, Field


class VisualType(str, Enum):
    """Categorization of diagram types."""
    # Engine A (Mermaid.js)
    FLOWCHART = "flowchart"
    GANTT = "gantt"
    TIMELINE = "timeline"
    MINDMAP = "mindmap"
    PIE = "pie"
    
    # Engine B (2D Parametric Vector Schematics)
    PLANTING_SPACING = "planting_spacing"
    DRIP_IRRIGATION = "drip_irrigation"
    RAISED_BED_PROFILE = "raised_bed_profile"
    CANOPY_PRUNING = "canopy_pruning"
    TRAP_DISTRIBUTION = "trap_distribution"
    CUSTOM_2D_SVG = "custom_2d_svg"


class DiagramRequest(BaseModel):
    """Input request to generate a diagram."""
    query: str = Field(..., description="Farmer prompt or instructions describing what to illustrate")
    visual_type: VisualType | None = Field(default=None, description="Explicit visual type or None for auto-detection")
    crop_name: str | None = Field(default=None, description="Target crop for contextual dimensions")
    language: str = Field(default="en", description="Target locale ('en', 'hi', etc.)")
    context_data: dict[str, Any] = Field(default_factory=dict, description="Metadata such as spacing, dimensions, stages")


class DiagramOutput(BaseModel):
    """Output generated by the diagram agent."""
    visual_type: VisualType
    engine_used: str = Field(..., description="'mermaid' or 'svg_2d'")
    raw_code: str = Field(..., description="Raw Mermaid code or SVG XML string")
    caption: str = Field(..., description="Bilingual caption explaining the schematic")
    bilingual_labels: dict[str, str] = Field(default_factory=dict)
    is_valid: bool = True
    validation_notes: str = ""
