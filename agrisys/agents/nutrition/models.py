"""Pydantic data models and schemas for Nutrition Deficiency Agent."""

from __future__ import annotations
from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field, field_validator


class SoilSensorReading(BaseModel):
    """Normalized soil sensor input reading."""
    nitrogen: float = Field(..., ge=0.0, le=1000.0, description="Available Soil Nitrogen in kg/ha")
    phosphorus: float = Field(..., ge=0.0, le=500.0, description="Available Soil Phosphorus in kg/ha")
    potassium: float = Field(..., ge=0.0, le=1000.0, description="Available Soil Potassium in kg/ha")
    ph: float = Field(..., ge=3.0, le=11.0, description="Soil pH (acidity / alkalinity)")
    electrical_conductivity: float = Field(..., ge=0.0, le=20.0, description="Electrical Conductivity in dS/m")
    soil_moisture: float = Field(..., ge=0.0, le=100.0, description="Volumetric Soil Moisture percentage")

    @field_validator("ph")
    @classmethod
    def validate_ph(cls, v: float) -> float:
        if v < 3.5 or v > 10.5:
            raise ValueError(f"Extremely unviable agronomic soil pH: {v}. Must be between 3.5 and 10.5.")
        return v

    def to_feature_vector(self) -> list[float]:
        """Returns ordered 6-dimensional sensor vector."""
        return [
            float(self.nitrogen),
            float(self.phosphorus),
            float(self.potassium),
            float(self.ph),
            float(self.electrical_conductivity),
            float(self.soil_moisture),
        ]


class DeficiencyPrediction(BaseModel):
    """Predicted nutrient deficiency status."""
    deficiency_class: str = Field(..., description="One of 12 agronomic deficiency classes")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Model prediction confidence")
    severity: Literal["Normal", "Mild", "Moderate", "Severe"] = Field(..., description="Deficiency severity level")
    affected_nutrient: str = Field(..., description="Key deficient element symbol: N, P, K, Ca, Mg, S, Fe, Zn, Mn, B, Cu, or None")
    visual_symptoms: str = Field(..., description="Observed or associated foliar symptom description")


class FertilizerDoseRecommendation(BaseModel):
    """Calculated elemental and commercial fertilizer requirements."""
    n_dose_kg_ha: float = Field(..., ge=0.0, description="Target elemental Nitrogen dose (kg/ha)")
    p_dose_kg_ha: float = Field(..., ge=0.0, description="Target elemental Phosphorus (P2O5) dose (kg/ha)")
    k_dose_kg_ha: float = Field(..., ge=0.0, description="Target elemental Potassium (K2O) dose (kg/ha)")
    
    # Commercial fertilizers (kg/ha)
    urea_kg_ha: float = Field(..., ge=0.0, description="Urea (46% N) required in kg/ha")
    dap_kg_ha: float = Field(..., ge=0.0, description="DAP (18% N, 46% P2O5) required in kg/ha")
    mop_kg_ha: float = Field(..., ge=0.0, description="MOP (60% K2O) required in kg/ha")

    # Commercial fertilizers per acre (1 ha ≈ 2.471 acres)
    urea_kg_acre: float = Field(..., ge=0.0, description="Urea in kg/acre")
    dap_kg_acre: float = Field(..., ge=0.0, description="DAP in kg/acre")
    mop_kg_acre: float = Field(..., ge=0.0, description="MOP in kg/acre")

    application_schedule: list[dict[str, str]] = Field(
        default_factory=list,
        description="Split application timing stages (Basal, Vegetative, Flowering)"
    )
    organic_alternatives: list[str] = Field(
        default_factory=list,
        description="Organic amendments (e.g. Vermicompost, FYM, Neem Cake, Biofertilizers)"
    )


class NutritionReport(BaseModel):
    """Complete diagnostic advisory generated by the Nutrition Deficiency Agent."""
    crop: str = Field(default="Unknown Crop", description="Host crop species")
    input_modality: Literal["multimodal", "sensor_only", "vision_only"] = Field(
        ..., description="Execution pathway depending on available input data"
    )
    sensor_evaluation: dict[str, str] = Field(
        default_factory=dict,
        description="Nutrient status rating per indicator (Low, Medium, High)"
    )
    prediction: DeficiencyPrediction
    fertilizer_recommendation: FertilizerDoseRecommendation
    advisory: str = Field(..., description="Actionable farmer advisory with timing and precautions")
    citations: list[str] = Field(default_factory=list, description="Authoritative references and ICAR guidelines")
